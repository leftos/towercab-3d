"""Feed the shipped apt.dat extractor a tiny synthetic apt.dat and print what it keeps."""
import importlib.util
import sys
from pathlib import Path

script = Path(sys.argv[1])
spec = importlib.util.spec_from_file_location("extract_airport_surfaces", script)
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)

APT = """I
1200 Generated by WorldEditor

1 100 0 0 TST1 Test one
110 1 0.25 0.00 Pavement A (square)
111 10.000 20.000
111 10.000 20.010
111 10.010 20.010
113 10.010 20.000
120 Taxi centerline drawn after pavement A
111 10.002 20.002 1
111 10.005 20.005 1
115 10.008 20.002
110 1 0.25 0.00 Pavement B (last pavement of the airport)
111 11.000 21.000
111 11.000 21.010
111 11.010 21.010
113 11.010 21.000
130 Airport boundary
111 9.990 19.990
111 9.990 21.020
111 11.020 21.020
113 11.020 19.990
1 200 0 0 TST2 Test two
110 2 0.25 0.00 Pavement C
112 12.000 22.000 12.001 22.001
112 12.000 22.010 12.001 22.011
112 12.010 22.010 12.011 22.011
114 12.010 22.000 12.011 22.001
1 300 0 0 TST3 Test three
99
"""

tmp = Path(sys.argv[2])
tmp.write_text(APT, encoding="latin-1")
airports = mod.parse_apt_dat(tmp)
out = mod.generate_output(airports)
for icao, a in out["airports"].items():
    print(icao, "pavements:", len(a["p"]))
    for p in a["p"]:
        print("   exterior", p["v"], "holes", p.get("h"))
for icao in ("TST1", "TST2"):
    if icao not in out["airports"]:
        print(icao, "MISSING from output")
