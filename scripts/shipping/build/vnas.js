#!/usr/bin/env node

/**
 * Points cargo at the private vNAS crate.
 *
 * The manifest depends on the in-repo stub (`src-tauri/vnas-stub`) so the crate
 * graph resolves for contributors without access to the private repository. A
 * vNAS build overrides that dependency with cargo's `[patch]`, keyed by the
 * stub's file URL and carrying the private repository:
 *
 *     [patch."file:///…/src-tauri/vnas-stub"]
 *     towercab-3d-vnas = { git = "https://github.com/Leftos/towercab-3d-vnas", branch = "master" }
 *
 * The patch reaches cargo as `--config <file.toml>` (local runs) or as the
 * checked-out `src-tauri/.cargo/config.toml` (CI, whose checkout is disposable),
 * and is never committed. Cargo rewrites `src-tauri/Cargo.lock` while the patch
 * is in effect, so every command run through here restores the lock afterwards.
 *
 * Setting TC3D_VNAS_CRATE_PATH to a local checkout of the private crate patches
 * that checkout in instead of the repository's `master`, for building against
 * unpushed crate changes:
 *
 *     towercab-3d-vnas = { path = "X:/dev/towercab-3d-vnas" }
 *
 * `--ci-config` ignores the variable and always writes the git patch.
 *
 * Usage:
 *   node scripts/shipping/build/vnas.js --ci-config
 *   node scripts/shipping/build/vnas.js cargo check --features vnas
 *   node scripts/shipping/build/vnas.js tauri build --features vnas
 *   TC3D_VNAS_CRATE_PATH=../towercab-3d-vnas node scripts/shipping/build/vnas.js cargo check --features vnas
 */

import { execSync } from 'child_process'
import fs from 'fs'
import path from 'path'
import { fileURLToPath, pathToFileURL } from 'url'

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = path.resolve(SCRIPT_DIR, '..', '..', '..')
const VNAS_STUB_DIR = path.join(REPO_ROOT, 'src-tauri', 'vnas-stub')
const CARGO_LOCK = path.join(REPO_ROOT, 'src-tauri', 'Cargo.lock')
const CI_CONFIG_PATH = path.join(REPO_ROOT, 'src-tauri', '.cargo', 'config.toml')
const DEFAULT_PATCH_PATH = path.join(REPO_ROOT, 'src-tauri', 'target', 'vnas-patch.toml')
const VNAS_REPO = 'https://github.com/Leftos/towercab-3d-vnas'
const ARG_SEPARATOR = ' -- '

/**
 * Write the `[patch]` table that swaps the in-repo stub for the private crate.
 * Patches in the checkout at `localCratePath` when one is given (by default
 * TC3D_VNAS_CRATE_PATH), otherwise the repository's `master`.
 * Returns the absolute path of the file written.
 */
export function writePatchConfig(
  targetPath = DEFAULT_PATCH_PATH,
  localCratePath = process.env.TC3D_VNAS_CRATE_PATH,
) {
  const stubUrl = pathToFileURL(VNAS_STUB_DIR).href
  const patchLine = localCratePath
    ? localCratePatchLine(localCratePath)
    : `towercab-3d-vnas = { git = "${VNAS_REPO}", branch = "master" }`
  const contents = [
    '# Generated by scripts/shipping/build/vnas.js - do not commit.',
    `[patch."${stubUrl}"]`,
    patchLine,
    '',
  ].join('\n')
  fs.mkdirSync(path.dirname(targetPath), { recursive: true })
  fs.writeFileSync(targetPath, contents)
  return path.resolve(targetPath)
}

/**
 * The patch line for a local checkout of the private crate. Throws when the
 * directory holds no Cargo.toml, so a mistyped path fails before cargo runs.
 */
function localCratePatchLine(localCratePath) {
  const crateDir = path.resolve(localCratePath)
  if (!fs.existsSync(path.join(crateDir, 'Cargo.toml'))) {
    throw new Error(
      `[vnas] TC3D_VNAS_CRATE_PATH is ${localCratePath}, but ${crateDir} has no Cargo.toml. ` +
        'Point it at a checkout of towercab-3d-vnas, or unset it to build against GitHub master.',
    )
  }
  const cratePath = crateDir.replaceAll('\\', '/')
  console.log(`[vnas] Using local crate at ${cratePath}`)
  return `towercab-3d-vnas = { path = "${cratePath}" }`
}

/**
 * Run a cargo or tauri command with the stub patched onto the private crate,
 * restoring Cargo.lock afterwards however the command ends.
 */
export function runWithVnas(command) {
  const patchPath = writePatchConfig()
  const savedLock = fs.existsSync(CARGO_LOCK) ? fs.readFileSync(CARGO_LOCK) : null
  const restoreLock = () => {
    if (savedLock !== null) {
      fs.writeFileSync(CARGO_LOCK, savedLock)
    }
  }
  // execSync's own error propagates after the finally below restores the lock.
  const onSignal = (signal) => {
    restoreLock()
    process.exit(signal === 'SIGINT' ? 130 : 143)
  }
  process.on('SIGINT', onSignal)
  process.on('SIGTERM', onSignal)
  try {
    execSync(withPatchConfig(command, patchPath), { stdio: 'inherit' })
  } finally {
    process.off('SIGINT', onSignal)
    process.off('SIGTERM', onSignal)
    restoreLock()
  }
}

/**
 * Add the patch to a command line. For `cargo …` it goes before any `--`, since
 * what follows that separator belongs to rustc or the test binary. For `tauri …`
 * it goes right after the first `--`, since tauri passes what follows to cargo.
 */
function withPatchConfig(command, patchPath) {
  const flag = `--config "${patchPath}"`
  const index = command.indexOf(ARG_SEPARATOR)
  if (!command.trimStart().startsWith('tauri')) {
    if (index === -1) {
      return `${command} ${flag}`
    }
    return `${command.slice(0, index)} ${flag}${command.slice(index)}`
  }
  if (index === -1) {
    return `${command}${ARG_SEPARATOR}${flag}`
  }
  const afterSeparator = index + ARG_SEPARATOR.length
  return `${command.slice(0, afterSeparator)}${flag} ${command.slice(afterSeparator)}`
}

function main() {
  const args = process.argv.slice(2)

  if (args[0] === '--ci-config') {
    console.log(`[vnas] Wrote ${writePatchConfig(CI_CONFIG_PATH, null)}`)
    return
  }

  if (args.length === 0) {
    console.error('Usage: node scripts/shipping/build/vnas.js [--ci-config | <cargo|tauri command…>]')
    process.exit(2)
  }

  runWithVnas(args.join(' '))
}

const isEntryPoint = Boolean(process.argv[1]) && pathToFileURL(process.argv[1]).href === import.meta.url

if (isEntryPoint) {
  try {
    main()
  } catch (error) {
    // execSync errors carry a status and have already printed through stdio.
    if (error.status === undefined) {
      console.error(error.message)
    }
    process.exit(error.status || 1)
  }
}
